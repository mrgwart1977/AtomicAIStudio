"""Application configuration.

All values come from environment variables (prefix ATOMIC_) or CLI flags.
No secrets or machine-specific paths are hardcoded; the desktop shell
passes --data-dir/--port/--token at launch and standalone dev defaults
to ./data relative to the backend package.
"""

from __future__ import annotations

import os
from pathlib import Path

from pydantic_settings import BaseSettings, SettingsConfigDict

# The "AtomicAIStudio" directory name predates the Atomic Dream Engine
# rebrand and is intentionally retained: renaming it would orphan the
# existing database, models, runtimes, and content-addressed assets.
_DEFAULT_DATA_DIR = Path(os.environ.get("LOCALAPPDATA", ".")) / "AtomicAIStudio"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="ATOMIC_")

    host: str = "127.0.0.1"
    port: int = 8788
    # Per-launch token generated by the desktop shell. "dev" is accepted
    # only because a standalone dev server has no shell to inject one.
    session_token: str = "dev"
    data_dir: Path = _DEFAULT_DATA_DIR
    cors_origins: list[str] = [
        "http://localhost:1420",
        "http://127.0.0.1:1420",
        "https://tauri.localhost",
        "http://tauri.localhost",
        "tauri://localhost",
    ]
    log_level: str = "INFO"
    # Optional command prefix for the inference worker — tests inject a
    # fake sd.cpp ("python tests/fake_sd.py"); production uses the
    # installed runtime binary under <data_dir>/runtimes/.
    sdcpp_cmd: str | None = None
    # Optional fixed models root; normally resolved per-call from the
    # app_settings row (models_dir) or data_dir/models.
    models_dir: Path | None = None
    # M4.1 worker pool policy — conservative caps; real persistent
    # adapters arrive in Phase 2. Values are env-overridable.
    worker_pool_max: int = 2
    worker_pool_per_gpu: int = 1
    worker_idle_s: float = 300.0
    # Phase 2A gate: registers the real persistent sd-server adapter.
    # Off by default — persistent inference is not yet validated (Phase
    # 2B). The subprocess-per-job adapter is unaffected.
    persistent_inference_enabled: bool = False

    @property
    def db_path(self) -> Path:
        return self.data_dir / "atomic.db"

    @property
    def db_url(self) -> str:
        return f"sqlite:///{self.db_path.as_posix()}"

    @property
    def assets_dir(self) -> Path:
        return self.data_dir / "assets"

    @property
    def backups_dir(self) -> Path:
        return self.data_dir / "backups"

    @property
    def logs_dir(self) -> Path:
        return self.data_dir / "logs"


def get_settings() -> Settings:
    return Settings()


def ensure_dirs(settings: Settings) -> None:
    for path in (settings.data_dir, settings.assets_dir, settings.backups_dir, settings.logs_dir):
        path.mkdir(parents=True, exist_ok=True)
