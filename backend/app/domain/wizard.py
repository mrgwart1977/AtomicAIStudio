"""A8 — beginner/advanced filmmaking wizard: derived workflow state.

The wizard owns NO rows and mutates nothing. Everything it reports is
derived from the real A1–A7 project data — screenplays, storyboard
scenes/shots/cast, keyframes, motion clips, dialogue segments,
assembly plans/items, timelines, assets, and generation jobs.
Progress itself persists in ``project.settings_json["wizard"]``,
written through the existing ``project.update_settings`` command
(preview → commit → audit → undo) — the same slot the earlier C5-D
guided flow used under ``"first_film"``, which is echoed back here as
``legacy_progress`` so upgraded projects resume honestly.

Generation-state honesty (A8.5): every produced asset in Phase A comes
from a mock adapter — the derivation labels result state from the
producing job's adapter kind (``simulated`` vs ``generated``) rather
than asserting either, plus draft/planned/missing/failed/cancelled/
stale/approved from real row state. When real adapters arrive the
labels keep working because they read provenance, not promises.
"""
from __future__ import annotations

from typing import Any

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.db.models import (
    AssemblyItem,
    AssemblyPlan,
    Asset,
    Character,
    GenerationJob,
    Keyframe,
    Location,
    MotionClip,
    Project,
    Scene,
    SceneCharacter,
    Screenplay,
    ScreenplayElement,
    ScreenplayScene,
    Shot,
    ShotCharacter,
    DialogueSegment,
    Timeline,
    TimelineClip,
)

#: The A8.2 guided stages, in order. ``required`` drives missing-input
#: warnings — navigation itself never hard-blocks on it.
STAGES: tuple[dict[str, Any], ...] = (
    {"id": "project", "label": "Project", "required": True},
    {"id": "film_settings", "label": "Film settings", "required": True},
    {"id": "screenplay", "label": "Screenplay", "required": True},
    {"id": "scenes", "label": "Scenes & dialogue", "required": True},
    {"id": "cast", "label": "Cast & continuity", "required": False},
    {"id": "shots", "label": "Storyboard shots", "required": True},
    {"id": "planning", "label": "Shot planning", "required": False},
    {"id": "keyframes", "label": "Keyframes", "required": False},
    {"id": "motion", "label": "Motion clips", "required": False},
    {"id": "dialogue", "label": "Dialogue & audio", "required": False},
    {"id": "assembly_plan", "label": "First-cut plan", "required": False},
    {"id": "assembly_apply", "label": "Review & apply", "required": False},
    {"id": "edit", "label": "Edit film", "required": False},
    {"id": "export_config", "label": "Export settings", "required": True},
    {"id": "export", "label": "Export & verify", "required": True},
)
STAGE_IDS = tuple(s["id"] for s in STAGES)

#: Generation states reported per entity (A8.5 vocabulary).
GEN_STATES = ("planned", "draft", "simulated", "generated", "missing",
              "failed", "cancelled", "stale", "approved")


def _jobs_by_id(session: Session, project_id: str) -> dict[str, GenerationJob]:
    rows = session.execute(
        select(GenerationJob).where(GenerationJob.project_id == project_id)
    ).scalars().all()
    return {j.id: j for j in rows}


def _asset_status(session: Session, asset_id: str | None) -> str | None:
    if not asset_id:
        return None
    row = session.get(Asset, asset_id)
    return row.status if row is not None else "missing"


def _gen_state(*, result_asset_id: str | None, job: GenerationJob | None,
               asset_status: str | None, entity_updated, prompt_edited: bool) -> str:
    """One honesty label for a generatable entity (keyframe, motion
    clip, dialogue segment). Priority order is deliberate:

    in-flight job → missing asset → failed/cancelled last job →
    stale (content edited after the producing job finished) →
    simulated/generated by adapter kind → draft (no result, no job).
    """
    if job is not None and job.status in ("queued", "running"):
        return "planned"
    if result_asset_id and asset_status in ("missing", "deleted"):
        return "missing"
    if job is not None and job.status == "failed":
        return "failed"
    if job is not None and job.status == "cancelled" and not result_asset_id:
        return "cancelled"
    if result_asset_id and prompt_edited:
        return "stale"
    if result_asset_id:
        if job is not None and job.adapter_id.startswith("mock."):
            return "simulated"
        if job is not None:
            return "generated"
        # result exists but the producing job row is gone — honest
        # fallback: we cannot prove provenance, say simulated only
        # when the asset carries mock provenance elsewhere; Phase A
        # has no real path, so report simulated with a caveat elsewhere.
        return "simulated"
    if job is not None and job.status == "cancelled":
        return "cancelled"
    return "draft"


def _edited_after(entity_updated, job: GenerationJob | None) -> bool:
    """True when the entity was edited after its producing job finished
    — a stale result, never silently regenerated."""
    if job is None or job.completed_at is None or entity_updated is None:
        return False
    try:
        return entity_updated > job.completed_at
    except TypeError:
        return False


def _entity_gen(session: Session, jobs: dict[str, GenerationJob],
                entity) -> dict[str, Any]:
    job = jobs.get(entity.generate_job_id or "")
    asset_status = _asset_status(session, entity.result_asset_id)
    state = _gen_state(
        result_asset_id=entity.result_asset_id, job=job,
        asset_status=asset_status,
        entity_updated=entity.updated_at,
        prompt_edited=_edited_after(entity.updated_at, job),
    )
    out = {
        "id": entity.id,
        "shot_id": getattr(entity, "shot_id", None),
        "state": state,
        "has_result": bool(entity.result_asset_id) and asset_status == "ready",
        "result_asset_id": entity.result_asset_id,
        "job_id": entity.generate_job_id,
        "job_status": job.status if job is not None else None,
        "job_adapter": job.adapter_id if job is not None else None,
        "revision": entity.revision,
    }
    if entity.status != "active":
        out["status"] = entity.status
    return out


def _count(session: Session, model, *where) -> int:
    return session.execute(
        select(func.count()).select_from(model).where(*where)
    ).scalar_one()


def wizard_state(session: Session, project: Project) -> dict[str, Any]:
    """Read-only derivation of the full workflow state for one project.

    Returned shape:
      stages:      [{id,index,label,required,status,summary,counts,warnings}]
      entities:    {keyframes:[...], clips:[...], dialogue:[...]} — per-row
                   generation-state labels for the honesty badges
      plans:       [{id,timeline_id,status,applied,stale,items{...}}]
      jobs:        recent generation jobs (id,kind,status,message,adapter)
      progress:    settings_json['wizard'] verbatim (client-owned blob)
      legacy_first_film: true when only the C5-D blob exists
      warnings:    project-level missing-input lines
      honesty:     {all_simulated, counts per GEN_STATE}
    """
    pid = project.id
    jobs = _jobs_by_id(session, pid)
    warnings: list[str] = []

    # ---------- raw project data (all project-scoped) ----------
    screenplays = session.execute(
        select(Screenplay).where(Screenplay.project_id == pid,
                                 Screenplay.status == "active")
        .order_by(Screenplay.position)).scalars().all()
    sp_scenes: list[ScreenplayScene] = []
    if screenplays:
        sp_scenes = session.execute(
            select(ScreenplayScene).where(
                ScreenplayScene.project_id == pid,
                ScreenplayScene.screenplay_id.in_([s.id for s in screenplays]))
            .order_by(ScreenplayScene.position)).scalars().all()
    dialogue_elements = _count(
        session, ScreenplayElement, ScreenplayElement.project_id == pid,
        ScreenplayElement.kind == "dialogue")

    scenes = session.execute(
        select(Scene).where(Scene.project_id == pid, Scene.status == "active")
        .order_by(Scene.position)).scalars().all()
    scene_ids = [s.id for s in scenes]
    shots = session.execute(
        select(Shot).where(Shot.project_id == pid, Shot.status == "active")
        .order_by(Shot.position)).scalars().all() if scene_ids else []
    shots = [s for s in shots if s.scene_id in scene_ids]
    shot_ids = [s.id for s in shots]

    characters = session.execute(
        select(Character).where(Character.project_id == pid,
                                Character.status == "active")).scalars().all()
    locations = session.execute(
        select(Location).where(Location.project_id == pid,
                               Location.status == "active")).scalars().all()
    cast_count = _count(session, SceneCharacter, SceneCharacter.project_id == pid)
    cast_count += _count(session, ShotCharacter, ShotCharacter.project_id == pid)

    keyframes = session.execute(
        select(Keyframe).where(Keyframe.project_id == pid,
                               Keyframe.status == "active")).scalars().all()
    clips = session.execute(
        select(MotionClip).where(MotionClip.project_id == pid,
                                 MotionClip.status == "active")).scalars().all()
    segments = session.execute(
        select(DialogueSegment).where(DialogueSegment.project_id == pid,
                                      DialogueSegment.status == "active")).scalars().all()

    plans = session.execute(
        select(AssemblyPlan).where(AssemblyPlan.project_id == pid)
        .order_by(AssemblyPlan.created_at.desc())).scalars().all()
    plan_items: dict[str, list[AssemblyItem]] = {}
    if plans:
        rows = session.execute(
            select(AssemblyItem).where(
                AssemblyItem.plan_id.in_([p.id for p in plans]))
            .order_by(AssemblyItem.position)).scalars().all()
        for it in rows:
            plan_items.setdefault(it.plan_id, []).append(it)

    timelines = session.execute(
        select(Timeline).where(Timeline.project_id == pid,
                               Timeline.status == "active")
        .order_by(Timeline.created_at)).scalars().all()
    tl_clip_counts: dict[str, int] = {}
    if timelines:
        for t in timelines:
            tl_clip_counts[t.id] = _count(
                session, TimelineClip, TimelineClip.timeline_id == t.id)

    export_jobs = [j for j in jobs.values()
                   if j.adapter_id == "ops.timeline.export"]
    export_jobs.sort(key=lambda j: j.created_at, reverse=True)

    # ---------- per-entity honesty ----------
    keyframe_rows = [_entity_gen(session, jobs, k) for k in keyframes]
    clip_rows = [_entity_gen(session, jobs, c) for c in clips]
    segment_rows = [_entity_gen(session, jobs, d) for d in segments]

    # unresolved speakers: segment with text but no live character link
    unresolved_speakers = sum(
        1 for d in segments if d.character_id is None and (d.text or "").strip())
    if unresolved_speakers:
        warnings.append(
            f"{unresolved_speakers} dialogue segment(s) have no character "
            "assigned — their speaker is unresolved.")

    # missing-asset lines (entities pointing at absent media)
    for label, rows in (("keyframe", keyframe_rows), ("motion clip", clip_rows),
                        ("dialogue segment", segment_rows)):
        n = sum(1 for r in rows if r["state"] == "missing")
        if n:
            warnings.append(f"{n} {label}(s) reference media that is missing "
                            "— re-generate or re-import before assembling.")

    # ---------- plans ----------
    plan_out: list[dict[str, Any]] = []
    latest_plan: dict[str, Any] | None = None
    for p in plans:
        items = plan_items.get(p.id, [])
        counts = {"pending": 0, "approved": 0, "rejected": 0, "skipped": 0,
                  "missing": 0}
        for it in items:
            counts[it.review_status] = counts.get(it.review_status, 0) + 1
            flags = it.flags_json or {}
            if flags.get("missing"):
                counts["missing"] += 1
        applied = bool(p.applied_json.get("fingerprint")) or p.status == "applied"
        # Staleness: the plan stores its computed sources fingerprint;
        # a cheap honesty signal is items whose source_json drifted —
        # the authoritative check still lives in assembly.apply itself.
        entry = {
            "id": p.id, "timeline_id": p.timeline_id, "name": p.name,
            "status": "applied" if applied else p.status,
            "applied": applied, "item_counts": counts,
            "items_total": len(items), "revision": p.revision,
            "created_at": p.created_at.isoformat() if p.created_at else None,
        }
        plan_out.append(entry)
        if latest_plan is None:
            latest_plan = entry

    # ---------- stage derivation ----------
    stage_status: dict[str, dict[str, Any]] = {}

    def put(sid: str, status: str, summary: str,
            counts: dict | None = None, warns: list[str] | None = None):
        stage_status[sid] = {"status": status, "summary": summary,
                             "counts": counts or {}, "warnings": warns or []}

    put("project", "done", f"Project '{project.name}' is open.",
        {"name": project.name})
    put("film_settings", "done",
        f"{project.aspect_ratio} · {project.width}×{project.height} · "
        f"{project.fps_num}/{project.fps_den} fps",
        {"aspect_ratio": project.aspect_ratio, "width": project.width,
         "height": project.height, "fps_num": project.fps_num,
         "fps_den": project.fps_den})

    if screenplays:
        n_el_scenes = len(sp_scenes)
        put("screenplay", "done",
            f"{len(screenplays)} screenplay(s), {n_el_scenes} scene(s).",
            {"screenplays": len(screenplays), "scenes": n_el_scenes,
             "screenplay_ids": [s.id for s in screenplays]})
    else:
        put("screenplay", "ready",
            "Create a screenplay to give your film a structure.",
            {"screenplays": 0}, ["No screenplay yet — required."])

    if scenes:
        put("scenes", "done", f"{len(scenes)} scene(s) on the storyboard.",
            {"scenes": len(scenes), "scene_ids": scene_ids,
             "dialogue_elements": dialogue_elements})
    else:
        put("scenes", "ready", "No scenes yet — scaffold from the "
            "screenplay or create one.", {"scenes": 0},
            ["No scenes yet — required."])

    if characters or cast_count:
        warns = []
        if not locations:
            warns.append("No locations yet — optional, but they help "
                         "continuity prompts.")
        put("cast", "done",
            f"{len(characters)} character(s), {cast_count} cast "
            f"assignment(s), {len(locations)} location(s).",
            {"characters": len(characters), "cast": cast_count,
             "locations": len(locations)}, warns)
    else:
        put("cast", "ready", "Add characters so shots know who is in "
            "frame.", {"characters": 0, "cast": 0, "locations": len(locations)},
            ["No characters yet — scenes will have no cast."])

    if shots:
        unplanned = sum(1 for s in shots if not (s.planning_json or {}))
        put("shots", "done", f"{len(shots)} shot(s) scaffolded.",
            {"shots": len(shots), "shot_ids": shot_ids})
        if unplanned == 0:
            put("planning", "done",
                f"All {len(shots)} shot(s) have camera/lighting planning.",
                {"planned": len(shots), "unplanned": 0})
        else:
            put("planning", "attention",
                f"{unplanned} of {len(shots)} shot(s) have no camera or "
                "lighting plan yet.", {"planned": len(shots) - unplanned,
                                       "unplanned": unplanned},
                [f"{unplanned} shot(s) still need planning — optional "
                 "but recommended."])
    else:
        put("shots", "ready", "No shots yet — scaffold the shot list.",
            {"shots": 0}, ["No shots yet — required."])
        put("planning", "blocked", "Add shots first.")

    def _gen_counts(rows: list[dict[str, Any]]) -> dict[str, int]:
        c: dict[str, int] = {"total": len(rows)}
        for r in rows:
            c[r["state"]] = c.get(r["state"], 0) + 1
        return c

    kf_counts = _gen_counts(keyframe_rows)
    kf_warns = []
    if shots:
        covered = {k.shot_id for k in keyframes}
        uncovered = len([s for s in shot_ids if s not in covered])
        if uncovered:
            kf_warns.append(f"{uncovered} shot(s) have no keyframe yet.")
    for state, label in (("failed", "keyframe job(s) failed — retry or edit "
                          "the prompt"), ("missing", "keyframe media is "
                          "missing"), ("stale", "keyframe result(s) are "
                          "stale — prompts changed since generation")):
        if kf_counts.get(state):
            kf_warns.append(f"{kf_counts[state]} {label}.")
    if keyframes:
        put("keyframes", "attention" if kf_warns and not kf_counts.get("simulated") else "done",
            f"{len(keyframes)} keyframe(s) — "
            + ", ".join(f"{v} {k}" for k, v in sorted(kf_counts.items())
                        if k != "total"),
            kf_counts, kf_warns)
    else:
        put("keyframes", "ready" if shots else "blocked",
            "Create start/end keyframes for your shots."
            if shots else "Add shots first.",
            kf_counts, kf_warns if shots else [])

    clip_counts = _gen_counts(clip_rows)
    clip_warns = []
    for state, label in (("failed", "motion-clip job(s) failed"),
                         ("missing", "motion-clip media is missing"),
                         ("stale", "motion-clip result(s) are stale")):
        if clip_counts.get(state):
            clip_warns.append(f"{clip_counts[state]} {label}.")
    if clips:
        put("motion", "attention" if clip_warns and not clip_counts.get("simulated") else "done",
            f"{len(clips)} motion clip(s) — "
            + ", ".join(f"{v} {k}" for k, v in sorted(clip_counts.items())
                        if k != "total"),
            clip_counts, clip_warns)
    else:
        put("motion", "ready" if keyframes else "blocked",
            "Prepare motion clips from your keyframes."
            if keyframes else "Create keyframes first.", clip_counts)

    seg_counts = _gen_counts(segment_rows)
    seg_warns = []
    if unresolved_speakers:
        seg_warns.append(f"{unresolved_speakers} segment(s) have no "
                         "speaker assigned.")
    if dialogue_elements and not segments:
        seg_warns.append(f"The screenplay has {dialogue_elements} dialogue "
                         "line(s) but no dialogue segments yet.")
    for state, label in (("failed", "dialogue job(s) failed"),
                         ("missing", "dialogue audio is missing"),
                         ("stale", "dialogue result(s) are stale")):
        if seg_counts.get(state):
            seg_warns.append(f"{seg_counts[state]} {label}.")
    if segments:
        put("dialogue", "attention" if seg_warns else "done",
            f"{len(segments)} dialogue segment(s) — "
            + ", ".join(f"{v} {k}" for k, v in sorted(seg_counts.items())
                        if k != "total"),
            seg_counts, seg_warns)
    else:
        put("dialogue", "ready" if (scenes or dialogue_elements) else "blocked",
            "Prepare dialogue and audio segments."
            if (scenes or dialogue_elements) else "Add scenes first.",
            seg_counts, seg_warns)

    if latest_plan is None:
        put("assembly_plan", "ready" if shots else "blocked",
            "Generate a first-cut assembly plan." if shots
            else "Add shots first.")
        put("assembly_apply", "blocked", "Create a plan first.")
    else:
        ic = latest_plan["item_counts"]
        put("assembly_plan", "done",
            f"Plan '{latest_plan['name']}' — {latest_plan['items_total']} "
            f"item(s), {ic.get('missing', 0)} flagged missing.",
            {"plan_id": latest_plan["id"], **ic})
        if latest_plan["applied"]:
            put("assembly_apply", "done",
                f"Plan applied — {ic.get('approved', 0)} approved item(s).",
                {"plan_id": latest_plan["id"], **ic})
        else:
            pending = ic.get("pending", 0)
            put("assembly_apply", "attention" if pending else "ready",
                f"{pending} item(s) still need review before applying."
                if pending else "All items reviewed — ready to apply.",
                {"plan_id": latest_plan["id"], **ic},
                [f"{pending} assembly item(s) unreviewed."] if pending else [])

    total_tl_clips = sum(tl_clip_counts.values())
    if timelines and total_tl_clips:
        put("edit", "done",
            f"{len(timelines)} timeline(s), {total_tl_clips} clip(s) "
            "placed.", {"timelines": len(timelines), "clips": total_tl_clips,
                        "timeline_ids": [t.id for t in timelines]})
    elif timelines:
        put("edit", "ready", "Timeline exists but has no clips yet — "
            "apply the assembly or edit manually.",
            {"timelines": len(timelines), "clips": 0,
             "timeline_ids": [t.id for t in timelines]})
    else:
        put("edit", "blocked", "A timeline is created when the assembly "
            "is applied or you make one.")

    if timelines:
        put("export_config", "done" if total_tl_clips else "ready",
            "Pick an export profile — the film is ready."
            if total_tl_clips else "Timeline is empty — export would "
            "produce nothing.",
            {"timelines": len(timelines)},
            [] if total_tl_clips else ["Timeline is empty — assemble or "
                                       "edit before exporting."])
    else:
        put("export_config", "blocked", "Build the film first.")

    if export_jobs:
        j = export_jobs[0]
        st = {"succeeded": "done", "failed": "attention",
              "cancelled": "attention"}.get(j.status, "attention")
        if j.status in ("queued", "running"):
            st = "attention"
        put("export", st,
            f"Last export {j.status} — {j.message or 'no message'}.",
            {"job_id": j.id, "job_status": j.status,
             "output_asset_id": j.output_asset_id},
            [] if j.status == "succeeded"
            else [f"Export {j.status} — see Jobs for details."])
    else:
        put("export", "ready" if total_tl_clips else "blocked",
            "Export your film when the cut is ready."
            if total_tl_clips else "Build the film first.")

    stages = []
    for i, s in enumerate(STAGES):
        d = stage_status.get(s["id"], {"status": "ready", "summary": "",
                                       "counts": {}, "warnings": []})
        stages.append({"id": s["id"], "index": i, "label": s["label"],
                       "required": s["required"], **d})

    honesty_counts: dict[str, int] = {}
    for rows in (keyframe_rows, clip_rows, segment_rows):
        for r in rows:
            honesty_counts[r["state"]] = honesty_counts.get(r["state"], 0) + 1
    produced = sum(honesty_counts.get(s, 0)
                   for s in ("simulated", "generated"))
    all_simulated = produced > 0 and honesty_counts.get("generated", 0) == 0

    recent_jobs = sorted(jobs.values(), key=lambda j: j.created_at,
                         reverse=True)[:25]
    settings = project.settings_json or {}
    return {
        "stages": stages,
        "entities": {"keyframes": keyframe_rows, "clips": clip_rows,
                     "dialogue": segment_rows},
        "plans": plan_out,
        "jobs": [{"id": j.id, "kind": j.kind, "adapter_id": j.adapter_id,
                  "status": j.status, "message": j.message,
                  "gpu_index": j.gpu_index,
                  "reserved_vram_bytes": j.reserved_vram_bytes,
                  "output_asset_id": j.output_asset_id,
                  "created_at": j.created_at.isoformat() if j.created_at else None}
                 for j in recent_jobs],
        "progress": settings.get("wizard"),
        "legacy_first_film": "wizard" not in settings and bool(settings.get("first_film")),
        "warnings": warnings,
        "honesty": {"all_simulated": all_simulated,
                    "counts": honesty_counts,
                    "note": "Phase A produces simulated output only — mock "
                            "adapters label every result. Nothing shown here "
                            "is real AI inference."},
        "revision": project.revision,
    }
